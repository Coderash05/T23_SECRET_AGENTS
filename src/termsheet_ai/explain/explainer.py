"""Plain-English Explainer for S5 Presentation and Audit Trace.

Transforms classified clauses, extracted facts, and symbolic rule justifications
into transparent, plain-English founder summaries with automated number consistency
and standard market exemplar citations retrieved via Stage S2 SBERT.

LLM-Powered RAG Mode (Member 4 — Stage S5)
-------------------------------------------
When an ``llm_callable`` is supplied, each clause summary is generated by Gemini
using a grounded RAG prompt that includes:

1. The verbatim clause text (source grounding).
2. Structured extracted facts from S3 (contractual attributes).
3. Symbolic risk flags and justification records from S4 (rule-engine conclusions).
4. A retrieved SBERT market exemplar from S2 when available (market norm context).

The model is instructed never to invent values not present in the provided context.
All numerical claims in the generated summary are subsequently verified by
``NumberConsistencyChecker``; if verification fails the summary falls back to the
deterministic template so that ``numbers_verified`` is always set correctly.

Fallback behaviour
------------------
If no ``llm_callable`` is supplied, or if the LLM raises an exception, the existing
deterministic template path is used unchanged.
"""

from __future__ import annotations

import logging
from typing import Any, Callable, Dict, List, Optional

from termsheet_ai.explain.consistency import NumberConsistencyChecker
from termsheet_ai.pipeline.base import BaseExplainer
from termsheet_ai.schemas.contracts import (
    AuditTrace,
    ClauseFamily,
    ClauseSpan,
    ClauseSummary,
    ExtractedFacts,
    RiskFlag,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Type alias — mirrors LLMCallable without circular import
# ---------------------------------------------------------------------------
_LLMCallable = Callable[[str], str]

# ---------------------------------------------------------------------------
# Prompt template for LLM-powered RAG summarization
# ---------------------------------------------------------------------------
_RAG_PROMPT_TEMPLATE = """\
You are a legal analyst helping startup founders understand venture-capital term sheet clauses.
Your task is to write a concise, founder-friendly plain-English summary of the clause below.

## Rules — strictly enforced
1. Only use facts explicitly stated in the CLAUSE TEXT or EXTRACTED FACTS sections.
2. If a fact is not present in the provided context, write "not specified" — never invent numbers, percentages, or legal conclusions.
3. If RISK FLAGS are provided, clearly explain what each risk means in plain English for the founder.
4. If a MARKET EXEMPLAR is provided, use it to explain how this clause compares to the market norm.
5. Keep the summary to 3–5 sentences. Use plain language, no legal jargon.
6. Do NOT reproduce the raw clause text verbatim — synthesize and explain it.
7. Begin directly with the explanation. Do not include headers, bullet points, or JSON.

---
CLAUSE ID: {clause_id}
CLAUSE FAMILY: {family}

CLAUSE TEXT:
{clause_text}

EXTRACTED FACTS:
{facts_text}

RISK FLAGS:
{flags_text}

MARKET EXEMPLAR (for comparison only — do not treat as this clause's terms):
{exemplar_text}
---

Write the founder-friendly summary now:"""


class PlainEnglishExplainer(BaseExplainer):
    """Generates founder-friendly explanations backed by NVCA citations and verified numbers.

    Parameters
    ----------
    checker:
        ``NumberConsistencyChecker`` instance. Created automatically when omitted.
    facts:
        Pre-wired ``ExtractedFacts`` container. Can also be passed at ``explain()``
        call time; call-time value takes precedence.
    retriever:
        Any object exposing ``retrieve_nearest_exemplars(clause, top_k)`` (e.g. the
        S2 ``SbertClassifier``). When *None*, no market exemplar is retrieved.
    llm_callable:
        A ``(prompt: str) -> str`` callable backed by Gemini (or any compatible
        LLM). When supplied, the explainer generates grounded RAG summaries using
        the LLM. When *None*, the deterministic template path is used for every clause.
    """

    def __init__(
        self,
        checker: Optional[NumberConsistencyChecker] = None,
        facts: Optional[ExtractedFacts] = None,
        retriever: Optional[Any] = None,
        llm_callable: Optional[_LLMCallable] = None,
    ):
        self.checker = checker or NumberConsistencyChecker()
        self.facts = facts
        self.retriever = retriever
        self.llm_callable = llm_callable

    # ------------------------------------------------------------------
    # Private helpers — retrieval and formatting
    # ------------------------------------------------------------------

    def _get_market_reference(self, clause: ClauseSpan) -> Optional[Dict[str, Any]]:
        """Retrieve standard market exemplar phrasing via SBERT ChromaDB index."""
        if self.retriever is not None and hasattr(self.retriever, "retrieve_nearest_exemplars"):
            try:
                results = self.retriever.retrieve_nearest_exemplars(clause, top_k=1)
                if results:
                    top = results[0]
                    # Only cite if similarity is solid and clause has an identified family
                    if (
                        top.get("cosine_similarity", 0.0) >= 0.35
                        and clause.detected_family != ClauseFamily.OTHER
                    ):
                        return top
            except Exception:
                pass
        return None

    @staticmethod
    def _format_facts_for_prompt(facts: Optional[ExtractedFacts]) -> str:
        """Render ``ExtractedFacts`` as human-readable key-value pairs for the prompt."""
        if facts is None:
            return "No structured facts extracted."
        lines: List[str] = []
        fact_map = {
            "Liquidation Preference": facts.liquidation_preference,
            "Anti-Dilution": facts.anti_dilution,
            "Board Composition": facts.board_composition,
            "Founder Vesting": facts.founder_vesting,
            "Protective Provisions": facts.protective_provisions,
        }
        for label, fact_obj in fact_map.items():
            if fact_obj is None:
                continue
            raw = (
                fact_obj.model_dump(exclude={"source_span", "is_grounded", "clause_id"})
                if hasattr(fact_obj, "model_dump")
                else fact_obj.dict(exclude={"source_span", "is_grounded", "clause_id"})
            )
            lines.append(f"{label}:")
            for k, v in raw.items():
                if v is not None and v != [] and v != {}:
                    lines.append(f"  {k}: {v}")
        for k, v in facts.custom_facts.items():
            lines.append(f"  {k}: {v}")
        return "\n".join(lines) if lines else "No structured facts extracted."

    @staticmethod
    def _format_flags_for_prompt(flags: List[RiskFlag]) -> str:
        """Render ``RiskFlag`` list as human-readable text for the prompt."""
        if not flags:
            return "No risk flags raised by the rule engine."
        parts: List[str] = []
        for f in flags:
            parts.append(
                f"[{f.severity.value.upper()}] {f.title}: {f.explanation} "
                f"(source: {f.market_standard_source})"
            )
        return "\n".join(parts)

    @staticmethod
    def _format_exemplar_for_prompt(market_ref: Optional[Dict[str, Any]]) -> str:
        """Render a retrieved SBERT exemplar as context text for the prompt."""
        if not market_ref:
            return "No market exemplar retrieved."
        source = market_ref.get("source", "unknown source")
        text = market_ref.get("text", "")
        similarity = market_ref.get("cosine_similarity", None)
        sim_str = f" (similarity: {similarity:.2f})" if similarity is not None else ""
        return f'From {source}{sim_str}: "{text}"'

    # ------------------------------------------------------------------
    # Private helpers — deterministic template (backward-compatible)
    # ------------------------------------------------------------------

    def _format_flag_explanation(
        self,
        clause: ClauseSpan,
        flag: RiskFlag,
        market_ref: Optional[Dict[str, Any]] = None,
    ) -> str:
        """Builds a structured plain-English explanation for a flagged term."""
        sev = flag.severity.value.upper()
        norm = flag.market_standard_source or "NVCA Model Term Sheet"

        explanation = (
            f"[{sev} RISK] {flag.title}: {flag.explanation} "
            f"Market standard: Under {norm}, this term deviates from conventional founder-friendly terms."
        )
        if market_ref:
            explanation += (
                f' Standard market reference ({market_ref["source"]}): "{market_ref["text"]}"'
            )
        return explanation

    def _build_template_summary(
        self,
        clause: ClauseSpan,
        clause_flags: List[RiskFlag],
        market_ref: Optional[Dict[str, Any]],
    ) -> tuple[str, Any]:
        """Return (summary_text, first_justification) using the deterministic template."""
        if clause_flags:
            details = " ".join(
                self._format_flag_explanation(clause, flag, market_ref) for flag in clause_flags
            )
            summary_text = (
                f"Clause {clause.clause_id} ({clause.detected_family.value}): {details}"
            )
            first_justification = clause_flags[0].justification
        else:
            family_name = clause.detected_family.value.replace("_", " ").title()
            summary_text = (
                f"Clause {clause.clause_id} ({clause.detected_family.value}): Standard {family_name} provision. "
                f"No non-standard or off-market risks detected against NVCA guidelines."
            )
            if market_ref:
                summary_text += (
                    f' Standard reference ({market_ref["source"]}): "{market_ref["text"]}"'
                )
            first_justification = None
        return summary_text, first_justification

    # ------------------------------------------------------------------
    # Private helper — LLM-powered RAG summary
    # ------------------------------------------------------------------

    def _build_llm_summary(
        self,
        clause: ClauseSpan,
        clause_flags: List[RiskFlag],
        market_ref: Optional[Dict[str, Any]],
        effective_facts: Optional[ExtractedFacts],
    ) -> Optional[str]:
        """Generate a Gemini RAG summary.  Returns *None* on any LLM failure."""
        assert self.llm_callable is not None  # guard: only called when llm_callable is set

        prompt = _RAG_PROMPT_TEMPLATE.format(
            clause_id=clause.clause_id,
            family=clause.detected_family.value.replace("_", " ").title(),
            clause_text=clause.raw_text.strip(),
            facts_text=self._format_facts_for_prompt(effective_facts),
            flags_text=self._format_flags_for_prompt(clause_flags),
            exemplar_text=self._format_exemplar_for_prompt(market_ref),
        )

        try:
            response = self.llm_callable(prompt)
            if response and response.strip():
                return response.strip()
            logger.warning(
                "LLM returned empty response for clause %s — falling back to template.",
                clause.clause_id,
            )
            return None
        except Exception as exc:
            logger.warning(
                "LLM call failed for clause %s (%s) — falling back to template.",
                clause.clause_id,
                exc,
            )
            return None

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def explain(
        self,
        clauses: List[ClauseSpan],
        audit_trace: AuditTrace,
        facts: Optional[ExtractedFacts] = None,
    ) -> List[ClauseSummary]:
        """Generate verified plain-English summaries alongside original clauses.

        When ``llm_callable`` is set, each clause is summarised via a grounded RAG
        prompt sent to Gemini.  Numbers in the LLM-generated text are verified by
        ``NumberConsistencyChecker``; on failure the deterministic template is used
        instead and ``numbers_verified`` is set accordingly.

        Parameters
        ----------
        clauses:
            All clause spans for this document (from S1/S2).
        audit_trace:
            Risk flags and justification records produced by S4.
        facts:
            Extracted facts from S3. Overrides any ``facts`` set at construction time.

        Returns
        -------
        List[ClauseSummary]
            One ``ClauseSummary`` per input clause, with ``numbers_verified`` truthfully set.
        """
        effective_facts = facts or self.facts
        flags_by_clause: dict[str, List[RiskFlag]] = {}
        for f in audit_trace.flags:
            flags_by_clause.setdefault(f.clause_id, []).append(f)

        summaries: List[ClauseSummary] = []

        for clause in clauses:
            clause_flags = flags_by_clause.get(clause.clause_id, [])
            market_ref = self._get_market_reference(clause)

            # Collect extra-allowed numbers from the exemplar so the checker
            # does not flag market-norm figures cited for comparison.
            allowed_extras: set[float] = set()
            if market_ref:
                if "text" in market_ref:
                    allowed_extras.update(self.checker.extract_numbers(market_ref["text"]))
                if "source" in market_ref:
                    allowed_extras.update(self.checker.extract_numbers(market_ref["source"]))

            # ----------------------------------------------------------------
            # Try LLM-powered RAG summary first
            # ----------------------------------------------------------------
            llm_text: Optional[str] = None
            if self.llm_callable is not None:
                llm_text = self._build_llm_summary(
                    clause, clause_flags, market_ref, effective_facts
                )

            # ----------------------------------------------------------------
            # Determine summary text and verification status
            # ----------------------------------------------------------------
            # Retrieve the first justification record for the template path; also
            # used by the checker to allow numbers from rule premises.
            _, first_justification = self._build_template_summary(
                clause, clause_flags, market_ref
            )

            if llm_text is not None:
                # Verify numbers in the LLM output
                verified, unverified = self.checker.verify_summary(
                    summary_text=llm_text,
                    clause=clause,
                    facts=effective_facts,
                    justification=first_justification,
                    allowed_extras=allowed_extras,
                )
                if verified:
                    summary_text = llm_text
                    numbers_verified = True
                    logger.debug(
                        "LLM summary accepted for clause %s (numbers verified).",
                        clause.clause_id,
                    )
                else:
                    # LLM introduced unverifiable numbers — fall back to template
                    logger.warning(
                        "LLM summary for clause %s contained unverified numbers %s; "
                        "using deterministic template.",
                        clause.clause_id,
                        unverified,
                    )
                    template_text, _ = self._build_template_summary(
                        clause, clause_flags, market_ref
                    )
                    verified_tmpl, _ = self.checker.verify_summary(
                        summary_text=template_text,
                        clause=clause,
                        facts=effective_facts,
                        justification=first_justification,
                        allowed_extras=allowed_extras,
                    )
                    summary_text = template_text
                    numbers_verified = verified_tmpl
            else:
                # Deterministic template path (no llm_callable or LLM failed)
                template_text, _ = self._build_template_summary(
                    clause, clause_flags, market_ref
                )
                verified_tmpl, _ = self.checker.verify_summary(
                    summary_text=template_text,
                    clause=clause,
                    facts=effective_facts,
                    justification=first_justification,
                    allowed_extras=allowed_extras,
                )
                summary_text = template_text
                numbers_verified = verified_tmpl

            summaries.append(
                ClauseSummary(
                    clause_id=clause.clause_id,
                    summary_text=summary_text,
                    numbers_verified=numbers_verified,
                )
            )

        return summaries
